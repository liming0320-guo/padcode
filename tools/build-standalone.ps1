$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
$inputPath = Join-Path $root "index.html"
$outputPath = Join-Path $root "PadCode-standalone.html"

$html = [System.IO.File]::ReadAllText($inputPath)
$html = [regex]::Replace($html, '\s*<link rel="manifest"[^>]*>\r?\n', "`n")
$html = [regex]::Replace($html, '\s*<link rel="icon"[^>]*>\r?\n', "`n")
$html = [regex]::Replace($html, '\s*<link rel="apple-touch-icon"[^>]*>\r?\n', "`n")

$stylesheetPaths = [System.Collections.Generic.List[string]]::new()
$html = [regex]::Replace(
  $html,
  '<link rel="stylesheet" href="([^"]+)"\s*/?>',
  {
    param($match)
    $stylesheetPaths.Add($match.Groups[1].Value)
    return ""
  }
)

$scriptPaths = [System.Collections.Generic.List[string]]::new()
$html = [regex]::Replace(
  $html,
  '<script src="([^"]+)"></script>',
  {
    param($match)
    $scriptPaths.Add($match.Groups[1].Value)
    return ""
  }
)

if ($stylesheetPaths.Count -eq 0 -or $scriptPaths.Count -eq 0) {
  throw "Could not find the expected stylesheet or script tags."
}

$cssParts = foreach ($relativePath in $stylesheetPaths) {
  [System.IO.File]::ReadAllText((Join-Path $root $relativePath))
}
$css = ($cssParts -join "`n`n").Replace("</style", "<\/style")

$javascriptParts = foreach ($relativePath in $scriptPaths) {
  [System.IO.File]::ReadAllText((Join-Path $root $relativePath))
}
$javascript = ($javascriptParts -join "`n`n").Replace("</script", "<\/script")

$html = $html.Replace(
  "</head>",
  "  <style>`n$css`n  </style>`n</head>"
)
$html = $html.Replace(
  "</body>",
  "  <script>`n$javascript`n  </script>`n</body>"
)
$html = [regex]::Replace(
  $html,
  "^<!doctype html>",
  "<!doctype html>`n<!-- PadCode standalone build. Generated by tools/build-standalone.ps1. -->",
  [System.Text.RegularExpressions.RegexOptions]::IgnoreCase
)

[System.IO.File]::WriteAllText(
  $outputPath,
  $html,
  [System.Text.UTF8Encoding]::new($false)
)

$size = [Math]::Round((Get-Item $outputPath).Length / 1KB)
Write-Output "Built $outputPath ($size KB)"
